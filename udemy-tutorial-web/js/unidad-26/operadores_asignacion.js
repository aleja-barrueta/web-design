// operador de asignacion a una variable (=)
let a = 1;

// operador de asignacion compuesto
a += 3; //a = a + 3
console.log(a);

a -= 2; //a = a - 2
console.log(a);

/*
ACTIVIDAD APLICAR OPERADORES DE ASIGNACION
*= 
%= 
**=
*/

a *= 2;
console.log(a);

a %= 6;
console.log(a);

a **= 2;
console.log(a);
